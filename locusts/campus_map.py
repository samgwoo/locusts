"""Building positions on the rendered campus map.

locusts/static/map is generated by tools/render_campus.py from data/map.osm. Coordinates are pixels in
campus.png.
"""

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path

MAP_DIR = Path(__file__).parent / "static" / "map"

Point = tuple[int, int]


@dataclass(frozen=True)
class CampusMap:
    width: int
    height: int
    attribution: str
    # Roof center of every named building, the spot a pet standing "at" that building is drawn.
    anchors: dict[str, Point]
    # Polygons that together cover each named building as drawn: its roof, its footprint, and the wall
    # between each pair of matching roof and footprint edges. Used for clicking and highlighting.
    shapes: dict[str, list[list[Point]]]


@cache
def load(map_dir: Path = MAP_DIR) -> CampusMap:
    data = json.loads((map_dir / "buildings.json").read_text())
    anchors: dict[str, Point] = {}
    shapes: dict[str, list[list[Point]]] = {}
    for b in data["buildings"]:
        if b["name"] and b["name"] not in anchors:
            roof = [(round(x), round(y)) for x, y in b["roof_px"][:-1]]
            foot = [(round(x), round(y)) for x, y in b["footprint_px"][:-1]]
            anchors[b["name"]] = (
                round(sum(x for x, _ in roof) / len(roof)),
                round(sum(y for _, y in roof) / len(roof)),
            )
            shapes[b["name"]] = building_shape(roof, foot)
    return CampusMap(data["width"], data["height"], data["attribution"], anchors, shapes)


def building_shape(roof: list[Point], foot: list[Point]) -> list[list[Point]]:
    """The renderer extrudes the footprint into the roof vertex by vertex, so edge i of each ring bounds wall i."""
    if len(roof) != len(foot):
        raise ValueError("roof and footprint rings must have the same number of vertices")
    walls = [[foot[i], foot[(i + 1) % len(foot)], roof[(i + 1) % len(roof)], roof[i]] for i in range(len(roof))]
    return [roof, foot, *walls]
